const LocaleContext = createContext<SupportedLocale>("vi");
export function LocaleProvider({
  locale,
  children,
}: {
  locale: SupportedLocale;
  children: React.ReactNode;
}) {
  return (
    <LocaleContext.Provider value={locale}>{children}</LocaleContext.Provider>
  );
}
function english(value: string) {
  const clean = value.replace(/\s+/g, " ").trim();
  const match = clean.match(/^(\d+\. )(.+)$/);
  return EN[clean] ?? (match ? match[1] + (EN[match[2]] ?? match[2]) : value);
}
export function useLocale() {
  const locale = useContext(LocaleContext);
  return useMemo(
    () => ({
      locale,
      t: (value: string, vars?: Record<string, string | number>) => {
        let out = locale === "en" ? english(value) : value;
        if (vars) {
          for (const [k, v] of Object.entries(vars))
            out = out.replaceAll(`{${k}}`, String(v));
        }
        return out;
      },
    }),
    [locale],
  );
}
